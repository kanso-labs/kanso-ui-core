#!/usr/bin/env node
// Generates src/tokens/design.tokens.css and src/tokens/defaults.ts from the
// W3C Design Tokens (DTCG) source in src/tokens/design.tokens.json, through
// Style Dictionary. Neither is committed: `build`, `lint` and `test` run this
// first, so there is no generated copy to edit by hand or to leave stale.
//
// design.tokens.css is the public override contract both libraries share, and
// it goes out as `./tokens.css`: every `--kui-*` custom property at its light
// value on `:root`, and the colours again at their dark value under
// `prefers-color-scheme: dark`. A consumer rethemes a component by redeclaring
// one of them, whatever their build tooling. The layout breakpoints are
// absent by design, since a media query cannot read a custom property — see
// the note on layout.breakpoint in design.tokens.json.
//
// defaults.ts is the same contract as data, for the main entry: `light` and
// `dark` map every property to its value in CSS syntax, exactly as the
// stylesheet declares it, and `KuiTheme` types a map of them. Both are read
// off the entries the stylesheet is written from, so the type names exactly
// the properties the stylesheet lists.
//
// The generators are kanso-ui's and react-native-kanso-ui's, which each built
// this contract from the same file until it moved here, and the stylesheet is
// byte for byte the one kanso-ui published.
//
// Run directly (`npm run tokens:build`), or import registerFormats and
// styleDictionaryConfig to drive the same build through Style Dictionary.
import { readFileSync } from 'node:fs'
import { format as oxfmtFormat } from 'oxfmt'
import StyleDictionary from 'style-dictionary'

/**
 * @typedef {import('style-dictionary/types').TransformedToken} TransformedToken
 * @typedef {[name: string, value: string]} Entry
 * @typedef {[name: string, light: string, dark: string]} ThemedEntry
 * @typedef {{ offsetX: string, offsetY: string, blur: string, spread: string, color: string }} ShadowLayer
 * @typedef {[x1: number, y1: number, x2: number, y2: number]} CubicBezier
 */

// The banner kanso-ui wrote, unchanged, so the stylesheet a consumer of either
// package reads is the one they have always read.
const CSS_BANNER = `/* AUTO-GENERATED by scripts/build-tokens.mjs from the sibling design.tokens.json.
   Do not hand-edit — change design.tokens.json and run \`npm run tokens:build\`.
   This is kanso-ui's public theming contract: override any custom property
   below (e.g. in your app's global stylesheet, after importing this file)
   to retheme every Kanso component — see the comment at the top of
   build-tokens.mjs. */

`

const DEFAULTS_BANNER = `// AUTO-GENERATED by scripts/build-tokens.mjs from the sibling design.tokens.json.
// Not committed and not to be edited: \`npm run tokens:build\` writes it.

`

// The CSS custom-property namespace every generated variable lives under,
// and the segment each token group maps to within it. Singular even where the
// group's name is plural (`radii`, `shadows`), as design systems name
// individual custom properties: `--kui-radius-lg`, not `--kui-radii-lg`.
const CSS_VAR_PREFIX = 'kui'
/** @type {Record<string, string>} */
const CSS_CATEGORY = {
  colors: 'color',
  motion: 'motion',
  radii: 'radius',
  shadows: 'shadow',
  sizing: 'sizing',
  spacing: 'spacing',
  stateLayerOpacity: 'state-layer-opacity',
  typography: 'typography',
}

// The token a value is an alias of — `{typography.fontFamily.brand}` names
// typography.fontFamily.brand — or undefined for a value that aliases none.
// Read off the token's original value, since style-dictionary has already
// resolved `$value` to the literal the alias stands for.
/** @param {TransformedToken[]} allTokens @param {...string} path @returns {string[] | undefined} */
function aliasOf(allTokens, ...path) {
  const joined = path.join('.')
  const token = allTokens.find((t) => t.path.join('.') === joined)
  if (!token) throw new Error(`Missing token: {${joined}}`)
  /** @type {unknown} */
  const original = token.original.$value
  const match =
    typeof original === 'string' ? /^\{([^}]+)\}$/u.exec(original) : null
  return match?.[1]?.split('.')
}

// $value is typed `any` by style-dictionary itself (a DTCG token's value is
// polymorphic depending on $type), so callers that need more than a plain
// string narrow the result through one of the type guards below.
/** @param {TransformedToken[]} allTokens @param {...string} path @returns {any} */
function byPath(allTokens, ...path) {
  const joined = path.join('.')
  const token = allTokens.find((t) => t.path.join('.') === joined)
  if (!token) throw new Error(`Missing token: {${joined}}`)
  return token.$value
}

/** @param {TransformedToken[]} allTokens @returns {string[]} */
function colorKeys(allTokens) {
  return [
    ...new Set(
      allTokens
        .filter((t) => t.path[0] === 'semantic' && t.path[1] === 'light')
        .map((t) => t.path[2]),
    ),
  ]
}

/** @param {TransformedToken[]} allTokens @returns {ThemedEntry[]} */
function colorThemedEntries(allTokens) {
  return colorKeys(allTokens).map((key) => [
    key,
    byPath(allTokens, 'semantic', 'light', key),
    byPath(allTokens, 'semantic', 'dark', key),
  ])
}

/** @param {string} group @param {string} key @returns {string} */
function cssVarName(group, key) {
  return `--${CSS_VAR_PREFIX}-${CSS_CATEGORY[group]}-${kebabCase(key)}`
}

/** @param {unknown} value @returns {value is CubicBezier} */
function isCubicBezier(value) {
  return (
    Array.isArray(value) &&
    value.length === 4 &&
    value.every((v) => typeof v === 'number')
  )
}

/** @param {unknown} value @returns {value is ShadowLayer} */
function isShadowLayer(value) {
  return (
    typeof value === 'object' &&
    value !== null &&
    'offsetX' in value &&
    typeof value.offsetX === 'string' &&
    'offsetY' in value &&
    typeof value.offsetY === 'string' &&
    'blur' in value &&
    typeof value.blur === 'string' &&
    'spread' in value &&
    typeof value.spread === 'string' &&
    'color' in value &&
    typeof value.color === 'string'
  )
}

/** @param {unknown} value @returns {value is ShadowLayer[]} */
function isShadowLayerArray(value) {
  return Array.isArray(value) && value.every(isShadowLayer)
}

/** @param {unknown} value @returns {value is string[]} */
function isStringArray(value) {
  return Array.isArray(value) && value.every((v) => typeof v === 'string')
}

/** @param {string} key @returns {string} */
function kebabCase(key) {
  return key.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)
}

/** @param {string} key @returns {string} */
function pascalCase(key) {
  return key.charAt(0).toUpperCase() + key.slice(1)
}

/** @param {string} fontName @returns {string} */
function quoteIfNeeded(fontName) {
  return fontName.includes(' ') ? `'${fontName}'` : fontName
}

/** @param {ShadowLayer[]} layers @returns {string} */
function serializeShadowLayers(layers) {
  return layers
    .map((l) => `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${l.color}`)
    .join(', ')
}

// Strips exactly one layer of matching outer quotes from a JS string literal,
// as the *Entries functions below write each value, to get the raw CSS value —
// "'400'" is 400, '"Roboto Flex, sans-serif"' is Roboto Flex, sans-serif. A
// font stack keeps its inner quotes, which CSS needs too for a family name
// with a space in it; only the outer delimiter comes off.
/** @param {string} jsLiteral @returns {string} */
function unquoteJsStringLiteral(jsLiteral) {
  const quote = jsLiteral[0]
  if ((quote === "'" || quote === '"') && jsLiteral.at(-1) === quote) {
    return jsLiteral.slice(1, -1)
  }
  return jsLiteral
}

// The full 15-style type scale (display/headline/title/body/label ×
// large/medium/small) — see typography.scale in design.tokens.json.
const SCALE_STYLES = [
  'displayLarge',
  'displayMedium',
  'displaySmall',
  'headlineLarge',
  'headlineMedium',
  'headlineSmall',
  'titleLarge',
  'titleMedium',
  'titleSmall',
  'bodyLarge',
  'bodyMedium',
  'bodySmall',
  'labelLarge',
  'labelMedium',
  'labelSmall',
]

/** @param {TransformedToken[]} allTokens @returns {Entry[]} */
function radiiEntries(allTokens) {
  const keys = ['none', 'xs', 'sm', 'md', 'lg', 'xl', 'pill', 'circle']
  return keys.map((key) => [
    key,
    `'${byPath(allTokens, 'radii', 'component', key)}'`,
  ])
}

// Elevation shadows render as a fixed black in both light and dark schemes
// — dark mode instead conveys elevation via the surface-container tones in
// semantic.*, not a shadow-opacity shift. So unlike colors, shadows need no
// light/dark split.
/** @param {TransformedToken[]} allTokens @param {string} level @returns {string} */
function shadowLayersAt(allTokens, level) {
  /** @type {unknown} */
  const value = byPath(allTokens, 'shadow', level)
  if (!isShadowLayerArray(value)) {
    throw new TypeError(`Expected ShadowLayer[] for shadow.${level}`)
  }
  return serializeShadowLayers(value)
}

/** @param {TransformedToken[]} allTokens @returns {Entry[]} */
function shadowsEntries(allTokens) {
  return ['1', '2', '3', '4', '5'].map((level) => [
    `elevation${level}`,
    `'${shadowLayersAt(allTokens, level)}'`,
  ])
}

// Flattened from the JSON's two families, control and row, into one record —
// `controlXs` here is `sizing.component.controlXs` there, and
// `--kui-sizing-control-xs` in the stylesheet.
/** @param {TransformedToken[]} allTokens @returns {Entry[]} */
function sizingEntries(allTokens) {
  const keys = [
    'controlXs',
    'controlSm',
    'controlMd',
    'controlLg',
    'controlXl',
    'controlXxl',
    'rowXs',
    'rowSm',
    'rowMd',
    'rowLg',
  ]
  return keys.map((key) => [
    key,
    `'${byPath(allTokens, 'sizing', 'component', key)}'`,
  ])
}

/** @param {TransformedToken[]} allTokens @returns {Entry[]} */
function spacingEntries(allTokens) {
  const keys = ['xxs', 'xs', 'sm', 'md', 'lg', 'xl', 'xxl', 'xxxl']
  return keys.map((key) => [
    key,
    `'${byPath(allTokens, 'spacing', 'component', key)}'`,
  ])
}

/** @param {TransformedToken[]} allTokens @returns {Entry[]} */
function typographyEntries(allTokens) {
  /** @type {Entry[]} */
  const entries = []
  for (const key of ['brand', 'plain', 'mono']) {
    /** @type {unknown} */
    const value = byPath(allTokens, 'typography', 'fontFamily', key)
    if (!isStringArray(value)) {
      throw new TypeError(`Expected string[] for typography.fontFamily.${key}`)
    }
    entries.push([
      `fontFamily${pascalCase(key)}`,
      `"${value.map(quoteIfNeeded).join(', ')}"`,
    ])
  }
  for (const key of ['regular', 'medium', 'bold']) {
    entries.push([
      `weight${pascalCase(key)}`,
      `'${byPath(allTokens, 'typography', 'fontWeight', key)}'`,
    ])
  }
  // A scale style's font and weight alias a typeface role and a weight —
  // display, headline and title the brand face, body and label the plain
  // one. The alias stays in the value, so the role's own property is read
  // first, then the typeface or weight it aliases, then the literal: a
  // consumer setting `--kui-typography-font-family-brand` changes every style
  // that uses the brand face.
  /** @param {string} style @param {string} field @param {string} group @param {string} value @returns {string} */
  const throughAlias = (style, field, group, value) => {
    const alias = aliasOf(allTokens, 'typography', 'scale', style, field)
    if (alias?.[0] !== 'typography' || alias[1] !== group || !alias[2]) {
      return value
    }
    const key = `${group === 'fontFamily' ? 'fontFamily' : 'weight'}${pascalCase(alias[2])}`
    return `var(${cssVarName('typography', key)}, ${value})`
  }
  for (const style of SCALE_STYLES) {
    /** @type {unknown} */
    const font = byPath(allTokens, 'typography', 'scale', style, 'font')
    if (!isStringArray(font)) {
      throw new TypeError(
        `Expected string[] for typography.scale.${style}.font`,
      )
    }
    const stack = font.map(quoteIfNeeded).join(', ')
    entries.push([
      `${style}Font`,
      `"${throughAlias(style, 'font', 'fontFamily', stack)}"`,
    ])
    for (const field of ['size', 'lineHeight', 'tracking']) {
      entries.push([
        `${style}${pascalCase(field)}`,
        `'${byPath(allTokens, 'typography', 'scale', style, field)}'`,
      ])
    }
    const weight = String(
      byPath(allTokens, 'typography', 'scale', style, 'weight'),
    )
    entries.push([
      `${style}Weight`,
      `'${throughAlias(style, 'weight', 'fontWeight', weight)}'`,
    ])
  }
  return entries
}

// Flattened to durationShort2 / easingStandard rather than kept nested,
// matching how typography collapses scale.labelLarge.size to labelLargeSize.
const DURATION_STEPS = [
  'short1',
  'short2',
  'short3',
  'medium1',
  'medium2',
  'medium3',
  'long1',
  'long2',
  'long3',
]

const EASING_CURVES = [
  'emphasized',
  'emphasizedDecelerate',
  'emphasizedAccelerate',
  'standard',
  'springFast',
  'springSlow',
]

/** @param {TransformedToken[]} allTokens @param {string} curve @returns {string} */
function cubicBezierAt(allTokens, curve) {
  /** @type {unknown} */
  const value = byPath(allTokens, 'motion', 'easing', curve)
  if (!isCubicBezier(value)) {
    throw new TypeError(
      `Expected [number, number, number, number] for motion.easing.${curve}`,
    )
  }
  return `cubic-bezier(${value.join(', ')})`
}

/** @param {TransformedToken[]} allTokens @returns {Entry[]} */
function motionEntries(allTokens) {
  return [
    ...DURATION_STEPS.map(
      /** @returns {Entry} */
      (step) => [
        `duration${pascalCase(step)}`,
        `'${byPath(allTokens, 'motion', 'duration', step)}'`,
      ],
    ),
    ...EASING_CURVES.map(
      /** @returns {Entry} */
      (curve) => [
        `easing${pascalCase(curve)}`,
        `'${cubicBezierAt(allTokens, curve)}'`,
      ],
    ),
  ]
}

/** @param {TransformedToken[]} allTokens @returns {Entry[]} */
function stateLayerOpacityEntries(allTokens) {
  const keys = [
    'hover',
    'focus',
    'pressed',
    'dragged',
    'disabledContainer',
    'disabledContent',
  ]
  return keys.map((key) => [
    key,
    `'${byPath(allTokens, 'stateLayerOpacity', key)}'`,
  ])
}

// Window size classes, smallest first — see layout.breakpoint in
// design.tokens.json.
const BREAKPOINTS = ['compact', 'medium', 'expanded', 'large', 'extraLarge']

// Strict about the unit, so a breakpoint written in anything but whole pixels
// fails the build here rather than reaching either library as NaN.
/** @param {TransformedToken[]} allTokens @param {string} key @returns {number} */
function breakpointAt(allTokens, key) {
  /** @type {unknown} */
  const value = byPath(allTokens, 'layout', 'breakpoint', key)
  const match =
    typeof value === 'string' ? /^(\d+(?:\.\d+)?)px$/u.exec(value) : null
  if (!match) {
    throw new TypeError(
      `Expected a length in px for layout.breakpoint.${key}, got '${String(value)}'`,
    )
  }
  return Number(match[1])
}

/** @param {unknown} value @returns {value is import('oxfmt').FormatConfig} */
function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

// oxfmt's format() doesn't read .oxfmtrc.json for programmatic callers — it
// only auto-discovers config for its CLI — so the repository's config is
// loaded and passed explicitly to keep generated output consistent with `npm
// run format`. The $schema key oxfmt itself doesn't declare is silently
// ignored, same as any other unknown key.
/** @type {unknown} */
const parsedOxfmtConfig = JSON.parse(
  readFileSync(new URL('../.oxfmtrc.json', import.meta.url), 'utf8'),
)
if (!isPlainObject(parsedOxfmtConfig)) {
  throw new TypeError('.oxfmtrc.json must contain a JSON object')
}
const oxfmtConfig = parsedOxfmtConfig

// Style Dictionary silently replaces a format registered again under the same
// name, so calling this more than once per process is safe.
export function registerFormats() {
  StyleDictionary.registerFormat({
    /** @param {import('style-dictionary/types').FormatFnArguments} args */
    format: async ({ dictionary }) =>
      prettify('design.tokens.css', cssSource(dictionary.allTokens)),
    name: 'css/design-tokens',
  })
  StyleDictionary.registerFormat({
    /** @param {import('style-dictionary/types').FormatFnArguments} args */
    format: async ({ dictionary }) =>
      prettify('defaults.ts', defaultsSource(dictionary.allTokens)),
    name: 'ts/token-defaults',
  })
}

/** @param {string} group @param {Entry[]} entries @returns {string[]} */
function cssLines(group, entries) {
  return entries.map(
    ([key, value]) =>
      `  ${cssVarName(group, key)}: ${unquoteJsStringLiteral(value)};`,
  )
}

// layout.breakpoint is absent by design, not by oversight: a custom property
// here would advertise an override that cannot work, since a media query
// cannot read one. Retheming a breakpoint means editing design.tokens.json,
// which is the honest story for a value a library has to compile in —
// everything else in this file really is overridable at runtime.
/** @param {TransformedToken[]} allTokens @returns {string} */
function cssSource(allTokens) {
  const themedEntries = colorThemedEntries(allTokens)
  const rootLines = [
    ...themedEntries.map(
      ([key, light]) => `  ${cssVarName('colors', key)}: ${light};`,
    ),
    ...cssLines('typography', typographyEntries(allTokens)),
    ...cssLines('spacing', spacingEntries(allTokens)),
    ...cssLines('radii', radiiEntries(allTokens)),
    ...cssLines('sizing', sizingEntries(allTokens)),
    ...cssLines('shadows', shadowsEntries(allTokens)),
    ...cssLines('stateLayerOpacity', stateLayerOpacityEntries(allTokens)),
    ...cssLines('motion', motionEntries(allTokens)),
  ].toSorted((a, b) => a.trim().localeCompare(b.trim()))
  const darkLines = themedEntries
    .map(([key, , dark]) => `    ${cssVarName('colors', key)}: ${dark};`)
    .toSorted((a, b) => a.trim().localeCompare(b.trim()))
  return `${CSS_BANNER}:root {
${rootLines.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root {
${darkLines.join('\n')}
  }
}
`
}

// The override contract as a type, a map of the `--kui-*` properties to CSS
// values with every one optional, and the light and dark defaults as values of
// it. Each property carries its default, so an editor shows what a property
// stands at before it is moved.
/** @param {TransformedToken[]} allTokens @returns {string} */
function defaultsSource(allTokens) {
  const properties = themeProperties(allTokens)
  const type = properties
    .map(([name, light, dark]) => {
      const value =
        light === dark
          ? `Defaults to \`${light}\`.`
          : `Defaults to \`${light}\` in the light scheme and \`${dark}\` in the dark.`
      return `  /** ${value} */\n  readonly '${name}'?: string`
    })
    .join('\n')
  const bounds = BREAKPOINTS.map(
    (key) => `  ${key}: ${breakpointAt(allTokens, key)},`,
  ).join('\n')
  return `${DEFAULTS_BANNER}/**
 * A theme: any of the \`--kui-*\` custom properties \`tokens.css\` lists, each set
 * to a value in CSS syntax. Hand one to \`ThemeScope\`'s \`theme\` prop, and every
 * component inside reads it.
 *
 * The values hold for both schemes. A theme with a value of its own for light
 * and for dark is two of these, with the scope handed the one for the scheme
 * in use.
 */
type KuiTheme = {
${type}
}

/** Every property at its value in the light scheme, as \`tokens.css\` declares it. */
const light: Required<KuiTheme> = {
${themeBlock(properties, 1)}
}

/**
 * Every property at its value in the dark scheme: the colours \`tokens.css\`
 * declares under \`prefers-color-scheme: dark\`, over every other property at
 * the one value it has in both.
 */
const dark: Required<KuiTheme> = {
${themeBlock(properties, 2)}
}

/**
 * The lower bound of each window size class, in px on the web and dp on
 * native, smallest first. A media query cannot read a custom property, so
 * neither library offers these as one to override, and \`tokens.css\` leaves
 * them out.
 */
const breakpoints = {
${bounds}
} as const

export { breakpoints, dark, light }
export type { KuiTheme }
`
}

// `filename` only has to carry the right extension: oxfmt picks its mode off
// it, and never reads the path.
/** @param {string} filename @param {string} source @returns {Promise<string>} */
async function prettify(filename, source) {
  const { code, errors } = await oxfmtFormat(filename, source, oxfmtConfig)
  if (errors.length > 0) {
    throw new Error(
      `oxfmt failed to format generated ${filename}: ${errors.map((e) => e.message).join('; ')}`,
    )
  }
  return code
}

/** @param {ThemedEntry[]} properties @param {1 | 2} index @returns {string} */
function themeBlock(properties, index) {
  return properties
    .map(
      (entry) =>
        `  ${JSON.stringify(entry[0])}: ${JSON.stringify(entry[index])},`,
    )
    .join('\n')
}

// Every property design.tokens.css declares, with its value in the light scheme
// and, for a colour, the dark. Read from the same entries cssSource writes, so
// the type and the maps below name exactly what that file lists.
/** @param {TransformedToken[]} allTokens @returns {ThemedEntry[]} */
function themeProperties(allTokens) {
  /** @type {Array<[string, Entry[]]>} */
  const groups = [
    ['typography', typographyEntries(allTokens)],
    ['spacing', spacingEntries(allTokens)],
    ['radii', radiiEntries(allTokens)],
    ['sizing', sizingEntries(allTokens)],
    ['shadows', shadowsEntries(allTokens)],
    ['stateLayerOpacity', stateLayerOpacityEntries(allTokens)],
    ['motion', motionEntries(allTokens)],
  ]
  return [
    ...colorThemedEntries(allTokens).map(
      /** @returns {ThemedEntry} */
      ([key, light, dark]) => [cssVarName('colors', key), light, dark],
    ),
    ...groups.flatMap(([group, entries]) =>
      entries.map(
        /** @returns {ThemedEntry} */
        ([key, value]) => {
          const raw = unquoteJsStringLiteral(value)
          return [cssVarName(group, key), raw, raw]
        },
      ),
    ),
  ].toSorted(([a], [b]) => a.localeCompare(b, 'en', { numeric: true }))
}

export const styleDictionaryConfig = {
  log: { verbosity: /** @type {const} */ ('silent') },
  platforms: {
    css: {
      buildPath: 'src/tokens/',
      files: [
        { destination: 'design.tokens.css', format: 'css/design-tokens' },
      ],
      // The formats key off `token.path`, not `token.name`. This only gives
      // every token a distinct name, so Style Dictionary's collision
      // warnings, aimed at formats that use the flat name, stay quiet.
      transforms: ['name/kebab'],
    },
    ts: {
      buildPath: 'src/tokens/',
      files: [{ destination: 'defaults.ts', format: 'ts/token-defaults' }],
      transforms: ['name/kebab'],
    },
  },
  source: ['src/tokens/design.tokens.json'],
  usesDtcg: true,
}

if (import.meta.main) {
  registerFormats()
  const sd = new StyleDictionary(styleDictionaryConfig)
  await sd.buildAllPlatforms()
}
